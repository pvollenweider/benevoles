export const DOC_INDEX_START = "<!-- doc-index:start (generated by npm run doc:index, do not edit) -->"
export const DOC_INDEX_END = "<!-- doc-index:end -->"

/** The list of `guide/README.md`: every unit by group, linked by file so it works on GitHub. */
export function docIndexMarkdown(units: readonly DocUnit[]): string {
  const sorted = sortDocUnits(units)
  const sections = DOC_GROUPS.flatMap((group) => {
    const inGroup = sorted.filter((u) => u.group === group.id)
    if (inGroup.length === 0) return []
    const items = inGroup.map((u) => `- [${u.title}](${u.slug}.md) : ${u.summary} Pour : ${docUnitAudience(u)}.`)
    return [`### ${group.title}\n\n${items.join("\n")}`]
  })
  return sections.length > 0 ? sections.join("\n\n") : "Aucune page pour l'instant."
}

/** `markdown` with its generated index replaced by `index`. */
export function withDocIndex(markdown: string, index: string): string {
  const i = markdown.indexOf(DOC_INDEX_START)
  const j = markdown.indexOf(DOC_INDEX_END)
  if (i === -1 || j === -1 || j < i) throw new Error("doc index markers missing")
  return `${markdown.slice(0, i + DOC_INDEX_START.length)}\n${index}\n${markdown.slice(j)}`
}
